# which joints each point follows. Along a limb the change-over at the elbow, wrist, knee and ankle goes by the distance
# down the limb. Where a limb leaves the trunk (shoulder, hip) it is spread over the skin itself: points clearly on the
# limb follow it, points clearly on the trunk do not, and in between the value is the average of its neighbours, so it
# fades evenly across the surface however the sculpt is shaped there.
ss = lambda v, lo, hi: (lambda t: t * t * (3 - 2 * t))(np.clip((v - lo) / (hi - lo), 0.0, 1.0))
E = np.concatenate([F[:, [0, 1]], F[:, [1, 2]], F[:, [2, 0]]])
