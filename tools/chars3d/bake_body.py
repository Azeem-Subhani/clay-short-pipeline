def spread(one, free):
    w = one.astype(float)
    e = E[free[E[:, 0]]]
    for _ in range(1500):
        w[free] = (np.bincount(e[:, 0], weights=w[e[:, 1]], minlength=len(V)) / deg)[free]
    return w


