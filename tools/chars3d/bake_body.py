def gap_x(sel, lo=0.0):
    """in a set of points: the widest gap between neighbours along x (from lo outward) -> (gap, x before it, x after it)"""
    xs = np.sort(x[sel])
    xs = xs[xs >= lo]
    if len(xs) < 4:
        return 0.0, 0.0, 0.0
    d = np.diff(xs)
    i = int(np.argmax(d))
    return float(d[i]), float(xs[i]), float(xs[i + 1])


