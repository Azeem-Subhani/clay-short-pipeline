"""bake_body.py - turn a sculpted body (a GLB from an image-to-3D model) into a body of the library (library/bodies).

    blender -b --factory-startup --python bake_body.py -- --src <body.glb> --name female_base [--pipeline <root>] [--check <abs.png>]

The sculpt must stand upright facing -Y with its arms held out from the body and its legs apart, and may have a
placeholder head (it is cut off at the neck: the figure's own head goes there). What is stored, in HEAD RADII with the
ground at z = 0 so it scales to any character: the skin (points, triangles), which joints each point follows, which
points are bare skin (from the sculpt's colours), and where the joints are. stagekit/body3d.py builds figures from it.

Found by measuring the sculpt: the neck (the narrowest place under the head), the crotch, the armpits, the line down
each arm and leg, the wrists (where skin colour starts) and the ankles (where the foot starts). --check renders the
sculpt with the joints marked, to look at before trusting it.
"""
