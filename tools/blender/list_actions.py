"""Write config/actions.json from stagekit.actions (the catalogue the director, the shot-builder and `clip.py actions` read).

    python tools/clip.py actions --rescan            (runs this inside Blender)

Hand-written fields of an existing entry are kept: "bodies" (what unusual bodies do instead) and "sources" (script beats).
A new action gets "bodies": {} and "sources": [] for you to fill in. An action that is gone from the code is reported.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from stagekit import actions, cast, core  # noqa: E402

path = core.PROJECT / "config" / "actions.json"
old = {a["name"]: a for a in json.loads(path.read_text(encoding="utf-8")).get("actions", [])} if path.exists() else {}
out = []
for a in actions.catalog():
    prev = old.get(a["name"], {})
    a["bodies"] = prev.get("bodies", {})
    a["sources"] = prev.get("sources", [])
    a["covers"] = prev.get("covers", [])
    out.append(a)
    if a["name"] not in old:
        print(f"new action: {a['name']} - fill in bodies / sources in config/actions.json")
for n in old:
    if n not in actions.ACTIONS:
        print(f"gone from stagekit.actions: {n}")
doc = {"_comment": "Named actions of stagekit.actions: actor.do(name, ...). Generated by `python tools/clip.py actions --rescan`; "
                   "'bodies', 'sources' and 'covers' are written by hand. See docs/ADDING_NEW_ACTIONS.md.",
       "poses": sorted(cast.POSES), "hand_shapes": list(cast.Actor.HAND_SHAPES), "actions": out}
path.write_text(json.dumps(doc, indent=1, ensure_ascii=False), encoding="utf-8")
print(f"config/actions.json: {len(out)} actions, {len(cast.POSES)} poses")
